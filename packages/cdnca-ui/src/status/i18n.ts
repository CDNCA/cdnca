export function messages(lang: Lang): Messages {
  return lang === 'en' ? en : zh
}

export function fill(template: string, values: Record<string, string>): string {
  return template.replace(/\{(\w+)\}/g, (match, key: string) => values[key] ?? match)
}

/** 分钟数写成「2 小时 5 分钟」。 */
export function duration(total: number, lang: Lang): string {
  const m = messages(lang)
  const hours = Math.floor(total / 60)
  const minutes = total % 60
  if (hours === 0) return fill(m.minutes, { n: String(minutes) })
  if (minutes === 0) return fill(m.hours, { h: String(hours) })
  return fill(m.hoursMinutes, { h: String(hours), m: String(minutes) })
}
