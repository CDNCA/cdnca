const (
	testCOSSecretID  = "AKIDTestOnlySecretID"
	testCOSSecretKey = "test-only-cos-secret-not-real"
	testCOSToken     = "test-only-cos-session-token"
)

func TestCOSVerifierSignsOnlyConfiguredHeadObject(t *testing.T) {
	recorder := &cosRoundTripper{responses: []cosResponse{{status: http.StatusOK}}}
	err := newCOSVerifier(2).verify(t.Context(), validCOSProbe(), validCOSCredentials(), controlledProviderClient(recorder))
	if err != nil {
		t.Fatalf("verify() error = %v", err)
	}

	requests := recorder.Requests()
	if len(requests) != 1 {
		t.Fatalf("request count = %d, want 1", len(requests))
	}
	request := requests[0]
	if request.Method != http.MethodHead {
		t.Fatalf("method = %q, want HEAD", request.Method)
	}
	if request.URL.Scheme != "https" || request.URL.Host != "cdnca-probe-1250000000.cos.ap-guangzhou.myqcloud.com" ||
		request.URL.Path != "/read-only/health.txt" {
		t.Fatal("request did not target the configured COS object")
	}
	authorization := request.Header.Get("Authorization")
	if !strings.Contains(authorization, "q-sign-algorithm=sha1") ||
		!strings.Contains(authorization, "q-ak="+testCOSSecretID) ||
		!strings.Contains(authorization, "q-signature=") {
		t.Fatal("Authorization header was not generated by the COS SDK")
	}
	if request.Header.Get("X-Cos-Security-Token") != testCOSToken {
		t.Fatal("session token header missing")
	}
	for _, secret := range []string{testCOSSecretID, testCOSSecretKey, testCOSToken} {
		if strings.Contains(request.URL.String(), secret) {
			t.Fatal("request URL contains credential material")
		}
	}
	if strings.Contains(authorization, testCOSSecretKey) || strings.Contains(authorization, testCOSToken) {
		t.Fatal("Authorization header contains secret material")
	}
}

func TestCOSVerifierRejectsInvalidConfigurationWithoutRequest(t *testing.T) {
	validProbe := validCOSProbe()
	validCredentials := validCOSCredentials()
	tests := []struct {
		name        string
		probe       Probe
		credentials originauthcontrol.CredentialSecret
		client      *http.Client
	}{
		{name: "disabled", probe: mutateCOSProbe(validProbe, func(value *Probe) { value.Enabled = false }), credentials: validCredentials, client: &http.Client{}},
		{name: "non tls", probe: mutateCOSProbe(validProbe, func(value *Probe) { value.Endpoint = "http://cos.example.test" }), credentials: validCredentials, client: &http.Client{}},
		{name: "endpoint path", probe: mutateCOSProbe(validProbe, func(value *Probe) { value.Endpoint += "/api" }), credentials: validCredentials, client: &http.Client{}},
		{name: "wrong endpoint bucket", probe: mutateCOSProbe(validProbe, func(value *Probe) { value.Bucket = "other-1250000000" }), credentials: validCredentials, client: &http.Client{}},
		{name: "wrong endpoint region", probe: mutateCOSProbe(validProbe, func(value *Probe) { value.Region = "ap-beijing" }), credentials: validCredentials, client: &http.Client{}},
		{name: "invalid bucket", probe: mutateCOSProbe(validProbe, func(value *Probe) { value.Bucket = "missing-app-id" }), credentials: validCredentials, client: &http.Client{}},
		{name: "object traversal", probe: mutateCOSProbe(validProbe, func(value *Probe) { value.Object = "a/../probe" }), credentials: validCredentials, client: &http.Client{}},
		{name: "missing secret id", probe: validProbe, credentials: mutateCOSCredential(validCredentials, func(value *originauthcontrol.CredentialSecret) { value.AccessKeyID = "" }), client: &http.Client{}},
		{name: "missing secret key", probe: validProbe, credentials: mutateCOSCredential(validCredentials, func(value *originauthcontrol.CredentialSecret) { value.SecretAccessKey = "" }), client: &http.Client{}},
		{name: "credential control", probe: validProbe, credentials: mutateCOSCredential(validCredentials, func(value *originauthcontrol.CredentialSecret) { value.SessionToken += "\r" }), client: &http.Client{}},
		{name: "nil client", probe: validProbe, credentials: validCredentials},
	}

	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			err := newCOSVerifier(2).verify(t.Context(), test.probe, test.credentials, test.client)
			if !errors.Is(err, ErrInvalidConfiguration) {
				t.Fatalf("verify() error = %v, want ErrInvalidConfiguration", err)
			}
			assertNoCOSSecret(t, err.Error(), test.probe, test.credentials)
		})
	}
}

func TestCOSVerifierClassifiesResponsesAndBoundsRetries(t *testing.T) {
	tests := []struct {
		name     string
		response cosResponse
		want     error
		attempts int
	}{
		{name: "invalid secret id", response: cosErrorResponse(http.StatusForbidden, "InvalidAccessKeyId"), want: ErrCredentialRejected, attempts: 1},
		{name: "signature mismatch", response: cosErrorResponse(http.StatusForbidden, "SignatureDoesNotMatch"), want: ErrCredentialRejected, attempts: 1},
		{name: "expired token", response: cosErrorResponse(http.StatusForbidden, "ExpiredToken"), want: ErrCredentialRejected, attempts: 1},
		{name: "access denied", response: cosErrorResponse(http.StatusForbidden, "AccessDenied"), want: ErrCredentialRejected, attempts: 1},
		{name: "missing bucket", response: cosErrorResponse(http.StatusNotFound, "NoSuchBucket"), want: ErrInvalidConfiguration, attempts: 1},
		{name: "missing object", response: cosErrorResponse(http.StatusNotFound, "NoSuchKey"), want: ErrInvalidConfiguration, attempts: 1},
		{name: "redirect", response: cosErrorResponse(http.StatusMovedPermanently, "PermanentRedirect"), want: ErrInvalidConfiguration, attempts: 1},
		{name: "throttled", response: cosErrorResponse(http.StatusTooManyRequests, "SlowDown"), want: ErrProviderUnavailable, attempts: 2},
		{name: "server error", response: cosErrorResponse(http.StatusServiceUnavailable, "ServiceUnavailable"), want: ErrProviderUnavailable, attempts: 2},
		{name: "transport", response: cosResponse{err: errors.New("sensitive transport failure")}, want: ErrProviderUnavailable, attempts: 2},
	}

	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			recorder := &cosRoundTripper{responses: []cosResponse{test.response}}
			err := newCOSVerifier(2).verify(t.Context(), validCOSProbe(), validCOSCredentials(), controlledProviderClient(recorder))
			if !errors.Is(err, test.want) {
				t.Fatalf("verify() error = %v, want %v", err, test.want)
			}
			if got := len(recorder.Requests()); got != test.attempts {
				t.Fatalf("request count = %d, want %d", got, test.attempts)
			}
			assertNoCOSSecret(t, err.Error(), validCOSProbe(), validCOSCredentials())
			if strings.Contains(err.Error(), "sensitive") {
				t.Fatal("verify() leaked provider response details")
			}
		})
	}
}

func TestCOSVerifierRecoversWithinRetryBudget(t *testing.T) {
	recorder := &cosRoundTripper{responses: []cosResponse{
		cosErrorResponse(http.StatusServiceUnavailable, "ServiceUnavailable"),
		{status: http.StatusOK},
	}}
	err := newCOSVerifier(2).verify(t.Context(), validCOSProbe(), validCOSCredentials(), controlledProviderClient(recorder))
	if err != nil {
		t.Fatalf("verify() error = %v", err)
	}
	if got := len(recorder.Requests()); got != 2 {
		t.Fatalf("request count = %d, want 2", got)
	}
}

func validCOSProbe() Probe {
	return Probe{
		Endpoint: "https://cdnca-probe-1250000000.cos.ap-guangzhou.myqcloud.com",
		Region:   "ap-guangzhou",
		Bucket:   "cdnca-probe-1250000000",
		Object:   "read-only/health.txt",
		Enabled:  true,
	}
}

func validCOSCredentials() originauthcontrol.CredentialSecret {
	return originauthcontrol.CredentialSecret{
		AccessKeyID:     testCOSSecretID,
		SecretAccessKey: testCOSSecretKey,
		SessionToken:    testCOSToken,
	}
}

func mutateCOSProbe(value Probe, mutate func(*Probe)) Probe {
	mutate(&value)
	return value
}

func mutateCOSCredential(value originauthcontrol.CredentialSecret, mutate func(*originauthcontrol.CredentialSecret)) originauthcontrol.CredentialSecret {
	mutate(&value)
	return value
}

func assertNoCOSSecret(t *testing.T, value string, probe Probe, credential originauthcontrol.CredentialSecret) {
	t.Helper()
	for _, sensitive := range []string{
		credential.AccessKeyID, credential.SecretAccessKey, credential.SessionToken,
		probe.Endpoint, probe.Bucket, probe.Object,
	} {
		if sensitive != "" && strings.Contains(value, sensitive) {
			t.Fatal("value contains sensitive verifier input")
		}
	}
}

type cosResponse struct {
	status int
	body   string
	err    error
}

func cosErrorResponse(status int, code string) cosResponse {
	return cosResponse{
		status: status,
		body:   fmt.Sprintf(`<Error><Code>%s</Code><Message>sensitive provider body</Message><RequestId>test</RequestId></Error>`, code),
	}
}

type cosRoundTripper struct {
	mu        sync.Mutex
	responses []cosResponse
	requests  []*http.Request
}

func (transport *cosRoundTripper) RoundTrip(request *http.Request) (*http.Response, error) {
	transport.mu.Lock()
	defer transport.mu.Unlock()
	transport.requests = append(transport.requests, request.Clone(request.Context()))
	index := len(transport.requests) - 1
	if index >= len(transport.responses) {
		index = len(transport.responses) - 1
	}
	response := transport.responses[index]
	if response.err != nil {
		return nil, response.err
	}
	return &http.Response{
		StatusCode: response.status,
		Status:     fmt.Sprintf("%d test", response.status),
		Header:     http.Header{"Content-Type": []string{"application/xml"}},
		Body:       io.NopCloser(strings.NewReader(response.body)),
		Request:    request,
	}, nil
}

func (transport *cosRoundTripper) Requests() []*http.Request {
	transport.mu.Lock()
	defer transport.mu.Unlock()
	return append([]*http.Request(nil), transport.requests...)
}

func controlledProviderClient(transport http.RoundTripper) *http.Client {
	return &http.Client{
		Transport: transport,
		CheckRedirect: func(*http.Request, []*http.Request) error {
			return http.ErrUseLastResponse
		},
	}
}
