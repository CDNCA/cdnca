package analyticslog

import (
	"os"
	"path/filepath"
	"regexp"
	"strings"
	"testing"
)

// The cluster DDL is a per-file mirror of infra/clickhouse/migrations
// (infra/clickhouse/replicated/generate.py; test_replicated_parity.py checks
// it is current). These helpers compare one mirror file with its single-node
// migration statement by statement, undoing only the two rewrites the
// generator makes: ON CLUSTER and the Replicated engine with its Keeper path.

const replicatedMirrorCluster = " ON CLUSTER cdnca_analytics"

var replicatedMirrorEngine = regexp.MustCompile(
	`Replicated(\w*MergeTree)\('/clickhouse/tables/\{shard\}/\{database\}/\{table\}', '\{replica\}'(?:, ([^)]*))?\)`)

// readReplicatedMirror returns the statements of replicated/<name> with the
// generator header removed and the cluster rewrites undone.
func readReplicatedMirror(t *testing.T, repoRoot, name string) []string {
	t.Helper()
	contents, err := os.ReadFile(filepath.Join(repoRoot, "infra", "clickhouse", "replicated", name))
	if err != nil {
		t.Fatalf("read replicated mirror %s: %v", name, err)
	}
	text := string(contents)
	header := "-- Generated by infra/clickhouse/replicated/generate.py from migrations/" + name + "; do not edit.\n" +
		"-- ON CLUSTER cdnca_analytics with Replicated engines; same statements and order as the single-node file.\n"
	if !strings.HasPrefix(text, header) {
		t.Fatalf("replicated mirror %s is not the generated file of migrations/%s", name, name)
	}
	statements := splitMigrationStatements(text[len(header):])
	for index, statement := range statements {
		statement = strings.ReplaceAll(statement, replicatedMirrorCluster, "")
		statements[index] = replicatedMirrorEngine.ReplaceAllStringFunc(statement, func(engine string) string {
			match := replicatedMirrorEngine.FindStringSubmatch(engine)
			if match[2] != "" {
				return match[1] + "(" + match[2] + ")"
			}
			return match[1]
		})
	}
	return statements
}

// splitMigrationStatements splits a comment-free migration file at the
// statement terminators (";" at the end of a line).
func splitMigrationStatements(sql string) []string {
	var statements []string
	for _, statement := range strings.Split(sql, ";\n") {
		if statement = strings.TrimSpace(strings.TrimSuffix(strings.TrimSpace(statement), ";")); statement != "" {
			statements = append(statements, statement)
		}
	}
	return statements
}

// assertReplicatedMirror fails unless replicated/<name> is the single-node
// migration <name> statement by statement.
func assertReplicatedMirror(t *testing.T, repoRoot, name, single string) {
	t.Helper()
	want := splitMigrationStatements(single)
	got := readReplicatedMirror(t, repoRoot, name)
	if len(want) == 0 || len(got) != len(want) {
		t.Fatalf("replicated mirror %s has %d statements, single-node migration has %d", name, len(got), len(want))
	}
	for index := range want {
		if got[index] != want[index] {
			t.Fatalf("replicated mirror %s statement %d drifted from the single-node migration:\n%s\nwant:\n%s",
				name, index+1, got[index], want[index])
		}
	}
}
