type SitePolicyMessages = typeof zhCN

function pseudoText(value: string): string {
  const expanded = value.split(/({{[^}]+}})/g).map((part) => part.startsWith('{{') ? part : [...part].map((char) => /\s/u.test(char) ? char : `${char}~`).join('')).join('')
  return `［${expanded}］`
}

function pseudoTree(tree: SitePolicyMessages): SitePolicyMessages {
  return Object.fromEntries(Object.entries(tree).map(([key, value]) => [key, pseudoText(value)])) as SitePolicyMessages
}

const pseudoCN = pseudoTree(zhCN)

export const sitePolicyMessages: Record<'zh-CN' | 'en-US' | 'qps-ploc' | 'qps-Ploc', SitePolicyMessages> = {
  'zh-CN': zhCN,
  'en-US': enUS,
  'qps-ploc': pseudoCN,
  'qps-Ploc': pseudoCN,
}

for (const [locale, messages] of Object.entries(sitePolicyMessages)) {
  i18n.addResourceBundle(locale, 'sitePolicy', messages, true, true)
}
