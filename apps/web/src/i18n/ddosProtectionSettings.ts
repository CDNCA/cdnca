function pseudo(value: string | TranslationTree): string | TranslationTree {
  if (typeof value === 'string') return `［${value.replace(/\S/g, '$&~')}］`
  return Object.fromEntries(Object.entries(value).map(([key, item]) => [key, pseudo(item)]))
}

