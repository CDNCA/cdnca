type MessageTree = { [key: string]: string | MessageTree }

function pseudo(value: MessageTree): MessageTree {
  return Object.fromEntries(Object.entries(value).map(([key, child]) => [
    key,
    typeof child === 'string'
      ? `［${child.split(/(\{\{[^}]+\}\})/u).map((part) => part.startsWith('{{') ? part : [...part].map((character) => /\s|\d/u.test(character) ? character : `${character}~`).join('')).join('')}］`
      : pseudo(child),
  ]))
}

