function pseudoText(value: string): string {
  const expanded = value.split(/({{[^}]+}}|<[^>]+>)/g).map((part) => {
    if (/^{{[^}]+}}$/.test(part) || /^<[^>]+>$/.test(part)) return part
    return [...part].map((character) => /\s/u.test(character) ? character : character.repeat(2)).join('')
  }).join('')
  return `［${expanded}］`
}

function pseudoTree(tree: TranslationTree): TranslationTree {
  return Object.fromEntries(Object.entries(tree).map(([key, value]) => [
    key,
    typeof value === 'string' ? pseudoText(value) : pseudoTree(value),
  ]))
}

export const pseudoNodeScheduling = pseudoTree(zhCNNodeScheduling)
