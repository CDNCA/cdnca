#!/usr/bin/env bash
# Static contract gate for the one-command control and edge installers.
#
# This test intentionally does not execute either installer: both scripts are
# root-only and perform network, package-manager, database and systemd writes.
# It verifies the safety and wiring contracts that must be true before an
# isolated Linux smoke host is used.
set -Eeuo pipefail

readonly ROOT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"
readonly CONTROL_SCRIPT="${ROOT_DIR}/scripts/install-control.sh"
readonly NODE_SCRIPT="${ROOT_DIR}/scripts/install-node.sh"

fail() {
  printf 'installers-static-test: %s\n' "$*" >&2
  exit 1
}

pass() {
  printf 'installers-static-test: %s\n' "$*"
}

[ -f "$CONTROL_SCRIPT" ] || fail "missing ${CONTROL_SCRIPT}"
[ -f "$NODE_SCRIPT" ] || fail "missing ${NODE_SCRIPT}"

for script in "$CONTROL_SCRIPT" "$NODE_SCRIPT"; do
  bash -n "$script" || fail "bash syntax check failed: $script"
done

command -v shellcheck >/dev/null 2>&1 || fail 'shellcheck is required'
shellcheck --severity=error "$CONTROL_SCRIPT" "$NODE_SCRIPT" ||
  fail 'shellcheck reported an error'

require_fixed() {
  local file=$1
  local text=$2
  local description=$3
  grep -Fq -- "$text" "$file" || fail "$description (missing: $text)"
}

require_regex() {
  local file=$1
  local expression=$2
  local description=$3
  grep -Eq -- "$expression" "$file" || fail "$description (pattern: $expression)"
}

require_any_fixed() {
  local file=$1
  local description=$2
  shift 2
  local text
  for text in "$@"; do
    if grep -Fq -- "$text" "$file"; then
      return 0
    fi
  done
  fail "$description (none of the expected forms were found)"
}

function_block() {
  # Installers keep functions at top level and close each function with a
  # standalone `}`.  Returning the block lets the assertions inspect a single
  # call path without matching unrelated helper functions.
  local function_name=$1
  local file=$2
  awk -v name="${function_name}" '
    $0 ~ "^" name "\\(\\) \\{" {inside=1}
    inside {print}
    inside && /^}$/ {exit}
  ' "$file"
}

require_block_fixed() {
  local function_name=$1
  local file=$2
  local text=$3
  local description=$4
  local block
  block=$(function_block "$function_name" "$file")
  [ -n "$block" ] || fail "missing function ${function_name} in ${file}"
  printf '%s\n' "$block" | grep -Fq -- "$text" || fail "$description (missing: $text)"
}

require_block_regex() {
  local function_name=$1
  local file=$2
  local expression=$3
  local description=$4
  local block
  block=$(function_block "$function_name" "$file")
  [ -n "$block" ] || fail "missing function ${function_name} in ${file}"
  printf '%s\n' "$block" | grep -Eq -- "$expression" || fail "$description (pattern: $expression)"
}

control_main=$(function_block main "$CONTROL_SCRIPT")
node_main=$(function_block main "$NODE_SCRIPT")
[ -n "$control_main" ] || fail 'missing control installer main function'
[ -n "$node_main" ] || fail 'missing node installer main function'

# cdncaCE: the community edition does not activate.  The installer records the
# installation locally (control-api install-community) and never contacts the
# licensing server's activation endpoint or takes an activation code.
for text in 'installations:activate' '--activation-code' 'ACTIVATION_CODE'; do
  if grep -Fq -- "$text" "$CONTROL_SCRIPT"; then
    fail "community control installer must not activate (found: $text)"
  fi
done
require_block_fixed install_community "$CONTROL_SCRIPT" 'install-community --installation-id "$INSTALLATION_ID"' 'community installer must record the installation through control-api install-community'
require_block_fixed install_community "$CONTROL_SCRIPT" '|| fail' 'a failed community installation record must stop installation'
# Ed25519 goes through the pinned static tool, never the host OpenSSL
# (docs/install/ed25519-tool-security.md).
require_fixed "$CONTROL_SCRIPT" '"$ED25519_TOOL" genkey "${KEY_DIR}/installation.key"' 'installation key must be generated by the pinned Ed25519 tool'
require_regex "$CONTROL_SCRIPT" '^readonly CDNCA_ED25519_TOOL_SHA256="[0-9a-f]{64}"$' 'control installer must pin the Ed25519 tool'
for script in "$CONTROL_SCRIPT" "$NODE_SCRIPT"; do
  if grep -Eq -- "pkeyutl|genpkey -algorithm (ED25519|ed25519|Ed25519)" "$script"; then
    fail "installer must not use OpenSSL for Ed25519: $script"
  fi
done
[ "$(sed -n 's/^readonly CDNCA_ED25519_TOOL_SHA256="\([0-9a-f]*\)"$/\1/p' "$CONTROL_SCRIPT")" = \
  "$(sed -n 's/^readonly CDNCA_ED25519_TOOL_SHA256="\([0-9a-f]*\)"$/\1/p' "$NODE_SCRIPT")" ] ||
  fail 'control and node installers must pin the same Ed25519 tool'

# The first administrator is an explicit installation input.  Do not silently
# create a fixed admin account, and do not accept the password in argv where it
# would be visible through ps(1) or shell history.
require_fixed "$CONTROL_SCRIPT" '--admin-username' 'control installer must expose administrator username input'
require_fixed "$CONTROL_SCRIPT" '--admin-password-file' 'control installer must expose owner-only administrator password input'
require_fixed "$CONTROL_SCRIPT" 'prompt_admin_username()' 'control installer must prompt for administrator username'
require_fixed "$CONTROL_SCRIPT" 'prompt_admin_password()' 'control installer must prompt for administrator password'
require_fixed "$CONTROL_SCRIPT" 'check_admin_password_policy "$ADMIN_PASSWORD" || fail' 'control installer must apply the shared password policy (libs/passwordpolicy) to the administrator password'
if grep -Eq -- '-ge 12 \] \|\| fail .administrator password' "$CONTROL_SCRIPT"; then
  fail 'control installer still enforces the old 12-character administrator password rule'
fi
require_fixed "$CONTROL_SCRIPT" 'fail "administrator bootstrap failed' 'administrator bootstrap failure must stop installation'
if grep -Eq -- --admin-password[[:space:]=] "$CONTROL_SCRIPT"; then
  fail 'control installer still accepts an administrator password on argv'
fi
bootstrap_block=$(function_block bootstrap_admin "$CONTROL_SCRIPT")
printf '%s\n' "$bootstrap_block" | grep -Fq -- '--username "$ADMIN_USERNAME"' ||
  fail 'bootstrap must use the requested administrator username'
printf '%s\n' "$bootstrap_block" | grep -Fq -- '|| fail' ||
  fail 'bootstrap must fail closed when the administrator cannot be created'

# The installer must prove the local PostgreSQL service and schema endpoint
# before migrations; RHEL-family fresh hosts need postgresql-setup --initdb.
database_block=$(function_block prepare_database "$CONTROL_SCRIPT")
printf '%s\n' "$database_block" | grep -Fq -- 'pg_isready' ||
  fail 'database preparation must wait for PostgreSQL readiness'
printf '%s\n' "$database_block" | grep -Fq -- '--initdb' ||
  fail 'database preparation must initialize a fresh RHEL PostgreSQL cluster'
printf '%s\n' "$database_block" | grep -Fq -- 'postgres-init.sql' ||
  fail 'database preparation must keep generated credentials out of psql argv'
printf '%s\n' "$database_block" | grep -Fq -- 'created PostgreSQL role/database cannot be accessed' ||
  fail 'database preparation must verify generated PostgreSQL credentials'
printf '%s\n' "$database_block" | grep -Fq -- "format('CREATE ROLE %I LOGIN PASSWORD %L'" ||
  fail 'local PostgreSQL role bootstrap must use escaped format() SQL'
printf '%s\n' "$database_block" | grep -Fq -- "'cdnca_control_app'" ||
  fail 'local PostgreSQL bootstrap must create the control application role required by migration 084'
printf '%s\n' "$database_block" | grep -Fq -- "'cdnca_plugin_webhook_runtime'" ||
  fail 'local PostgreSQL bootstrap must create the plugin webhook runtime role required by migration 084'
printf '%s\n' "$database_block" | grep -Fq -- "'cdnca_control_runtime'" ||
  fail 'local PostgreSQL bootstrap must create the control runtime role required by migration 229'
printf '%s\n' "$database_block" | grep -Fq -- '\connect cdnca' ||
  fail 'local PostgreSQL bootstrap must connect to the application database before changing schema ownership'
printf '%s\n' "$database_block" | grep -Fq -- 'ALTER SCHEMA public OWNER TO cdnca' ||
  fail 'local PostgreSQL bootstrap must make the application role the public schema owner required by migration 084'
printf '%s\n' "$database_block" | grep -Fq -- 'REVOKE ALL ON SCHEMA public FROM PUBLIC' ||
  fail 'local PostgreSQL bootstrap must remove the public schema ACL drift rejected by migration 084'
printf '%s\n' "$database_block" | grep -Fq -- '\gexec' ||
  fail 'local PostgreSQL role bootstrap must execute generated SQL with gexec'
printf '%s\n' "$database_block" | grep -Fq -- ' <"$sql_file"' ||
  fail 'local PostgreSQL bootstrap must stream root-only SQL through postgres stdin'
if printf '%s\n' "$database_block" | grep -Fq -- '--file "$sql_file"'; then
  fail 'local PostgreSQL bootstrap must not ask postgres to read the root-only SQL path'
fi
if printf '%s\n' "$database_block" | grep -Fq -- "PASSWORD :'cdnca_password'"; then
  fail 'local PostgreSQL bootstrap must not interpolate a psql variable inside DO $$'
fi

control_env_block=$(function_block write_environment "$CONTROL_SCRIPT")
[ -n "$control_env_block" ] || fail 'missing control write_environment function'

# The control API contract is deliberately explicit.  These fields carry the
# runtime key material and broker/Redis endpoints required by serve; merely
# declaring the variables at the top of the script is not enough.
control_env_fields=(
  ACCESS_TOKEN_SECRET
  IMPERSONATION_HMAC_KEY_BASE64
  OPENRESTY_SECURITY_SECRET_KEY_BASE64
  OBSERVABILITY_LOG_CURSOR_KEY_BASE64
  MFA_ENABLED=true
  ORIGIN_AUTH_RUNTIME_ENABLED=false
