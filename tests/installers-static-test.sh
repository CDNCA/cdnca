  CACHE_CONTROL_RUNTIME_COMMAND_STREAM=AGENT_COMMANDS
  CACHE_CONTROL_RUNTIME_STATUS_STREAM=AGENT_DEPLOYMENT_STATUS
  'CACHE_CONTROL_RUNTIME_CURSOR_KEY_BASE64=${CACHE_CONTROL_CURSOR_KEY_BASE64}'
)
for field in "${control_env_fields[@]}"; do
  printf '%s\n' "$control_env_block" | grep -Fq -- "$field" ||
    fail "control.env does not write required field ${field}"
done

# The complete release must be wired into main.  This catches the dangerous
# state where helper functions exist but a real install only provisions the
# old control-api slice.
for helper in generate_pki generate_runtime_secrets download_nats_binaries download_native_support prepare_native_baseline download_node_assets write_web_runtime_config write_environment setup_native_upgrade; do
  printf '%s\n' "$control_main" | grep -Eq -- "(^|[^A-Za-z0-9_])${helper}[[:space:]]*([[:space:]]|$|\()" ||
    fail "control installer main does not call ${helper}"
done
community_line=$(printf '%s\n' "$control_main" | awk '$1 == "install_community" {print NR; exit}')
[ -n "$community_line" ] || fail 'control installer community installation record call is missing'
for helper in download_native_support prepare_native_baseline; do
  verification_line=$(printf '%s\n' "$control_main" | awk -v name="$helper" '$1 == name {print NR; exit}')
  [ -n "$verification_line" ] && [ "$verification_line" -lt "$community_line" ] ||
    fail "${helper} must finish before the community installation record is written"
done
require_block_fixed download_native_support "$CONTROL_SCRIPT" 'verify_native_install_package' 'complete management package must pass the independent signed verifier'
require_block_fixed download_native_support "$CONTROL_SCRIPT" 'required_schema=cdnca.native-management.install/v2' 'public management installs must require the source-free signed format'
require_block_fixed prepare_native_baseline "$CONTROL_SCRIPT" 'install-native-baseline.py" check' 'baseline archive must be validated before executing the Control binary'
require_block_fixed prepare_native_baseline "$CONTROL_SCRIPT" '--stage-directory' 'Control must execute from the verified private baseline stage'

# Node upgrades: the runtime is configured with two distinct root-only Ed25519
# signing keys whose public halves are published with a digest the copied node
# command pins.  cdncaCE: online upgrades need license-issued grants, so the
# runtime stays off and no entitlement trust file is configured.
require_block_fixed write_environment "$CONTROL_SCRIPT" 'CONTROL_UPGRADE_RUNTIME_ENABLED=false' 'community control.env must keep license-granted online upgrades off'
require_block_regex write_environment "$CONTROL_SCRIPT" '^LICENSE_SERVICE_URL=$' 'community control.env must not name a license service'
require_block_fixed write_environment "$CONTROL_SCRIPT" 'ENTITLEMENT_TRUSTED_KEYS_FILE=${CONFIG_DIR}/entitlement-trusted-keys.json' \
  'community control.env must pin the public signing keys write_upgrade_trust writes (no lease is ever read)'
require_fixed "$CONTROL_SCRIPT" 'write_upgrade_trust' 'community installer must write the pinned public signing keys'
for field in CONTROL_UPGRADE_NATS_NAME= CONTROL_UPGRADE_WORKER_ID= \
  'CONTROL_UPGRADE_COMMAND_GRANT_TRUST_FILE=${CONFIG_DIR}/entitlement-trusted-keys.json' \
  CONTROL_UPGRADE_CONTROL_SIGNING_KEY_ID= 'CONTROL_UPGRADE_CONTROL_SIGNING_PRIVATE_KEY_FILE=${UPGRADE_KEY_DIR}/control-execution.pem' \
  CONTROL_UPGRADE_EDGE_SIGNING_KEY_ID= 'CONTROL_UPGRADE_EDGE_SIGNING_PRIVATE_KEY_FILE=${UPGRADE_KEY_DIR}/edge-execution.pem' \
  CONTROL_UPGRADE_COMMAND_ISSUANCE_TTL= CONTROL_UPGRADE_EXECUTION_TTL= CONTROL_UPGRADE_ACTIVATION_TIMEOUT= \
  CONTROL_UPGRADE_OBSERVATION_WINDOW= CONTROL_UPGRADE_HEALTH_INTERVAL= CONTROL_UPGRADE_PROBE_TIMEOUT= \
  CONTROL_UPGRADE_REQUIRED_CONSECUTIVE_SUCCESSES= CONTROL_UPGRADE_NATS_CONNECT_TIMEOUT= \
  CONTROL_UPGRADE_NATS_RECONNECT_WAIT= CONTROL_UPGRADE_NATS_DRAIN_TIMEOUT= CONTROL_UPGRADE_SHUTDOWN_TIMEOUT= \
  'CONTROL_UPGRADE_ARTIFACT_CACHE_DIR=${DOWNLOAD_DIR}/edge-agent/upgrades/sha256' \
  'CONTROL_UPGRADE_ARTIFACT_BASE_URL=$(upgrade_download_origin)/downloads/edge-agent/upgrades/sha256'; do
  require_block_fixed write_environment "$CONTROL_SCRIPT" "$field" "control.env must configure the node upgrade runtime (${field})"
done
require_block_fixed publish_upgrade_trust "$CONTROL_SCRIPT" '"$ED25519_TOOL" genkey "$control_key"' 'upgrade signing keys must be generated Ed25519 keys'
# Plugin webhook attestation key: generated at install, never empty in control.env.
printf '%s\n' "$control_main" | grep -Eq '^[[:space:]]*generate_plugin_webhook_attestation_key$' ||
  fail 'control installer main does not generate the plugin webhook attestation key'
require_block_fixed generate_plugin_webhook_attestation_key "$CONTROL_SCRIPT" '"$ED25519_TOOL" genkey "$key"' 'plugin webhook attestation key must be a generated Ed25519 key'
require_block_fixed generate_plugin_webhook_attestation_key "$CONTROL_SCRIPT" 'chmod 0400 "$key"' 'plugin webhook attestation key must be root read-only'
for field in PLUGIN_WEBHOOK_ATTESTATION_KEY_ID=plugin-webhook-attestation-v1 \
  'PLUGIN_WEBHOOK_ATTESTATION_PRIVATE_KEY_FILE=${KEY_DIR}/plugin-webhook-attestation-v1.pem'; do
  require_block_fixed write_environment "$CONTROL_SCRIPT" "$field" "control.env must name the plugin webhook attestation key (${field})"
done
require_block_fixed publish_upgrade_trust "$CONTROL_SCRIPT" 'chmod 0400 "$control_key" "$edge_key"' 'upgrade signing private keys must be root read-only'
require_block_fixed publish_upgrade_trust "$CONTROL_SCRIPT" 'cmp -s "$TEMP_DIR/control-execution.pub.pem" "$TEMP_DIR/edge-execution.pub.pem"' 'control and edge upgrade keys must be distinct'
# Schema, artifact_trust and the download policy: services/control-api/internal/nativebackup/nodeinstalltrust.go.
require_fixed "$ROOT_DIR/services/control-api/internal/nativebackup/nodeinstalltrust.go" 'nodeInstallTrustSchema  = "cdnca.edge-upgrade-trust/v1"' 'upgrade trust must use the documented schema'
require_block_fixed publish_upgrade_trust "$CONTROL_SCRIPT" '${DOWNLOAD_DIR}/edge-agent/upgrade-trust.json' 'upgrade trust must be published beside the node artifacts'
# Nodes download upgrade artifacts from this control plane, never the licensing server.
# fix-btenv4: control-api builds the document from control.env (artifact base URL = control plane origin
# or the BaoTa direct port, root from upgrade_download_root_ca_file), the same code a migration restore uses.
require_block_fixed publish_upgrade_trust "$CONTROL_SCRIPT" '"$CONTROL_BINARY" native-backup publish-node-install-trust' 'node upgrade trust must be built by control-api from control.env'
require_block_fixed upgrade_download_root_ca_file "$CONTROL_SCRIPT" "printf '%s' \"\${PKI_DIR}/root-ca-cert.pem\"" 'private-CA control planes must embed their root for node upgrade downloads'
! function_block publish_upgrade_trust "$CONTROL_SCRIPT" | grep -Fq 'LICENSING_SERVER' ||
  fail 'node upgrade trust must not point nodes at the licensing server'
require_block_fixed write_web_runtime_config "$CONTROL_SCRIPT" 'window.__CDNCA_NODE_UPGRADE_TRUST_SHA256__' 'Web runtime must expose the upgrade trust digest'
upgrade_trust_line=$(printf '%s\n' "$control_main" | awk '$1 == "publish_upgrade_trust" {print NR; exit}')
environment_line=$(printf '%s\n' "$control_main" | awk '$1 == "write_environment" {print NR; exit}')
web_runtime_line=$(printf '%s\n' "$control_main" | awk '$1 == "write_web_runtime_config" {print NR; exit}')
node_assets_line=$(printf '%s\n' "$control_main" | awk '$1 == "download_node_assets" {print NR; exit}')
control_runtime_line=$(printf '%s\n' "$control_main" | awk '$1 == "configure_control_runtime" {print NR; exit}')
# fix-r1c: artifact_trust pins artifacts.json after configure_control_runtime merged the publisher key.
[ -n "$upgrade_trust_line" ] && [ "$node_assets_line" -lt "$upgrade_trust_line" ] &&
  [ "$control_runtime_line" -lt "$upgrade_trust_line" ] && [ "$upgrade_trust_line" -lt "$community_line" ] &&
  [ "$environment_line" -lt "$upgrade_trust_line" ] && [ "$upgrade_trust_line" -lt "$web_runtime_line" ] ||
  fail 'upgrade trust must be published after the publisher key joins artifacts.json, before the community installation record and Web runtime configuration'
require_fixed "$ROOT_DIR/services/control-api/internal/nativebackup/nodeinstalltrust.go" 'ArtifactTrust    nodeTrustKeys' 'upgrade trust must pin the artifact keys of this installation'


# Enrollment and steady-state agent traffic are separate TLS listeners.  Keep
# the two ports distinct all the way from defaults to the actual edge-agent
# commands/configuration.
# Ports are not pinned (the control installer picks them, ADR 0013 §3.5);
# every deployment must keep its listener, published and public ports equal
# and the two ports distinct.
node_enrollment_port=$(sed -n 's/^GATEWAY_ENROLLMENT_PORT="\([0-9]*\)"$/\1/p' "$NODE_SCRIPT")
node_agent_port=$(sed -n 's/^GATEWAY_PORT="\([0-9]*\)"$/\1/p' "$NODE_SCRIPT")
[ -n "$node_enrollment_port" ] && [ -n "$node_agent_port" ] && [ "$node_enrollment_port" != "$node_agent_port" ] ||
  fail 'node installer fallback Gateway ports must be two distinct numbers'
compose_enrollment_port=$(sed -n 's/^ *CDNCA_GATEWAY_ENROLLMENT_ADDR: :\([0-9]*\)$/\1/p' "$ROOT_DIR/compose.full.yaml")
compose_agent_port=$(sed -n 's/^ *CDNCA_GATEWAY_AGENT_ADDR: :\([0-9]*\)$/\1/p' "$ROOT_DIR/compose.full.yaml")
[ -n "$compose_enrollment_port" ] && [ -n "$compose_agent_port" ] && [ "$compose_enrollment_port" != "$compose_agent_port" ] ||
  fail 'Compose Gateway listeners must use two distinct ports'
