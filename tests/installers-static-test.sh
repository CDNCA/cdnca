  NODE_CA_CERTIFICATE_CHAIN_FILE
  NODE_CA_PRIVATE_KEY_FILE
  CDNCA_GATEWAY_CLIENT_CA_CERT_FILE
  CDNCA_GATEWAY_CLIENT_CA_KEY_FILE
  CDNCA_GATEWAY_ROOT_CA_CERT_FILE
  CDNCA_GATEWAY_ROOT_CA_KEY_FILE
  EDGE_DEPLOYMENT_NATS_URL
