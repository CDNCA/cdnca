require_fixed "$ROOT_DIR/compose.full.yaml" "AGENT_GATEWAY_ENROLLMENT_PORT:-${compose_enrollment_port}}:${compose_enrollment_port}" 'Compose published enrollment port must match its listener'
require_fixed "$ROOT_DIR/compose.full.yaml" "AGENT_GATEWAY_PUBLIC_ENDPOINT:-localhost:${compose_agent_port}}" 'Compose public endpoint must use the Agent listener port'
for helm_values in "$ROOT_DIR/infra/helm/cdnca/values.yaml" "$ROOT_DIR/infra/helm/cdnca/values-ha.yaml"; do
  helm_enrollment_port=$(sed -n 's/^ *enrollmentPort: \([0-9]*\)$/\1/p' "$helm_values" | head -n 1)
  helm_agent_port=$(sed -n 's/^ *agentPort: \([0-9]*\)$/\1/p' "$helm_values" | head -n 1)
  [ -n "$helm_enrollment_port" ] && [ -n "$helm_agent_port" ] && [ "$helm_enrollment_port" != "$helm_agent_port" ] ||
    fail "Helm ${helm_values##*/} Gateway ports must be two distinct numbers"
done
helm_agent_port=$(sed -n 's/^ *agentPort: \([0-9]*\)$/\1/p' "$ROOT_DIR/infra/helm/cdnca/values.yaml" | head -n 1)
require_fixed "$ROOT_DIR/infra/helm/cdnca/values.yaml" "agentPublicEndpoint: gateway.example.invalid:${helm_agent_port}" 'Helm default public endpoint must use the Agent port'
# The copied node command no longer embeds Gateway ports in the Web page; the
# control installer publishes them through /downloads/node-install-defaults.
require_fixed "$CONTROL_SCRIPT" "printf 'gateway_enrollment_address=%s:%s\\n' \"\$gateway_host\" \"\$GATEWAY_ENROLLMENT_PORT\"" 'published node install defaults must use the selected enrollment port'
require_fixed "$CONTROL_SCRIPT" "printf 'gateway_address=%s:%s\\n' \"\$gateway_host\" \"\$GATEWAY_AGENT_PORT\"" 'published node install defaults must use the selected Agent port'
require_fixed "$NODE_SCRIPT" '--control-plane-ca-sha256' 'node bootstrap must expose a pinned management CA digest'
require_fixed "$NODE_SCRIPT" 'prepare_control_plane_ca' 'node installer must prepare management HTTPS trust before downloading artifacts'
require_fixed "$NODE_SCRIPT" '--cacert "$CONTROL_PLANE_CA_FILE"' 'management downloads must use the verified CA bundle'
# fz-x12: the node takes its region from the control plane (key document
# node_region); the installer has no region option and writes none.
! grep -Eq -- '--node-region|NODE_REGION|node_region' "$NODE_SCRIPT" ||
  fail 'node installer must not take or write a node region (the control plane sends it)'
require_fixed "$NODE_SCRIPT" 'verify_ca_file "$candidate"' 'self-signed management CA bootstrap must verify the downloaded certificate'
require_fixed "$NODE_SCRIPT" 'CONTROL_PLANE_CA_SHA256' 'self-signed management CA bootstrap must require a fixed SHA-256 pin'
if grep -Eq -- 'curl[[:space:]]+-k([[:space:]]|$)' "$NODE_SCRIPT"; then
  fail 'node installer must not use an unpinned curl -k download'
fi
require_regex "$NODE_SCRIPT" 'GATEWAY_ENROLLMENT_ADDRESS=.*GATEWAY_ENROLLMENT_PORT' 'node must derive enrollment address from enrollment port'
require_regex "$NODE_SCRIPT" 'GATEWAY_ADDRESS=.*GATEWAY_PORT' 'node must derive agent address from agent port'
