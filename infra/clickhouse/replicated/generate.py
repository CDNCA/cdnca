#!/usr/bin/env python3
"""Generate the ON CLUSTER mirror of infra/clickhouse/migrations into this directory.

Every NNN_name.{up,down}.sql under migrations/ gets a same-named file here,
rewritten statement by statement with the migrator's own cluster_statement
(scripts/clickhouse-migrate): ON CLUSTER <cluster>, *MergeTree ->
Replicated*MergeTree('/clickhouse/tables/{shard}/{database}/{table}', '{replica}', ...).
SELECT guards (throwIf) run unchanged on the node they are sent to.
Backfill INSERT ... SELECT reads and writes shard-local tables: run each file
on the first replica of every shard (the migrator does this itself).

  python3 infra/clickhouse/replicated/generate.py          # rewrite files
  python3 infra/clickhouse/replicated/generate.py --check  # exit 1 when stale
"""
import importlib.util
from pathlib import Path
import re
import sys

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[2]
SOURCE = REPO / "infra" / "clickhouse" / "migrations"
CLUSTER = "cdnca_analytics"
SELECT = re.compile(r"^\s*SELECT\b", re.I)
DROP_TABLE = re.compile(r"^\s*DROP\s+TABLE\b", re.I)
SYNC = re.compile(r"\bSYNC\s*$", re.I)


def load_migrator():
    path = REPO / "scripts" / "clickhouse-migrate" / "cdnca-clickhouse-migrate.py"
    spec = importlib.util.spec_from_file_location("cdnca_clickhouse_migrate", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def cluster(statement, migrator):
    if SELECT.match(statement):
        return statement
    statement = migrator.cluster_statement(statement, CLUSTER)
    # Without SYNC an Atomic database keeps a dropped Replicated table's Keeper
    # replica path until the delayed drop, so an immediate re-apply of the up
    # file fails with REPLICA_ALREADY_EXISTS.
    if DROP_TABLE.match(statement) and not SYNC.search(statement):
        statement += " SYNC"
    return statement


def render(source, migrator):
    statements = [cluster(statement, migrator)
                  for statement in migrator.CH.native_clickhouse_statements(source.read_text(encoding="utf-8"))]
    header = (f"-- Generated by infra/clickhouse/replicated/generate.py from migrations/{source.name}; do not edit.\n"
              f"-- ON CLUSTER {CLUSTER} with Replicated engines; same statements and order as the single-node file.\n")
    return header + "".join(f"\n{statement};\n" for statement in statements)


def expected():
    migrator = load_migrator()
    return {source.name: render(source, migrator) for source in sorted(SOURCE.glob("*.sql"))}


def main(argv):
    files = expected()
    current = {path.name: path.read_text(encoding="utf-8") for path in HERE.glob("*.sql")}
    if "--check" in argv:
        stale = sorted(name for name in files.keys() | current.keys() if files.get(name) != current.get(name))
        for name in stale:
            print(f"stale: {name}", file=sys.stderr)
        return 1 if stale else 0
    for name in current.keys() - files.keys():
        (HERE / name).unlink()
    for name, text in files.items():
        (HERE / name).write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
