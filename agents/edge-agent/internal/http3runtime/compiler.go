package http3runtime

import (
	"fmt"
	"net/netip"
	"strings"
)

const (
	releaseTLSDirectory    = "tls"
	releaseCertificateFile = "server.crt"
	releasePrivateKeyFile  = "server.key"
	releaseQUICHostKeyFile = "quic-host.key"
	releaseCertificatePath = releaseTLSDirectory + "/" + releaseCertificateFile
	releasePrivateKeyPath  = releaseTLSDirectory + "/" + releasePrivateKeyFile
	nginxTemporaryRoot     = "/var/lib/cdnca-edge-http3/run/nginx-temp"
	// nginx 默认值。它同时决定每连接帧配额 (3+2)*size/2000，不能跟随请求头上限缩小，
	// 否则小 request_header_bytes 下响应帧不够发，报 "quic flood detected"。
	// 请求头上限由 client_header_buffer_size/large_client_header_buffers 约束。
	http3StreamBufferBytes = 65_536
)

func Compile(policy Policy) (CompiledPolicy, error) {
	normalized, digest, canonical, err := normalize(policy)
	if err != nil {
		return CompiledPolicy{}, err
	}
	return CompiledPolicy{
		Policy: normalized, Digest: digest, CanonicalJSON: canonical,
		NginxConfig: render(normalized, digest),
	}, nil
}

func render(policy Policy, digest string) []byte {
	listen := nginxAddress(policy.Listener.Address, policy.Listener.Port)
	var output strings.Builder
	fmt.Fprintf(&output, "# Generated by CDNCA edge-agent; do not edit.\n")
	fmt.Fprintf(&output, "# schema=%s version=%s digest=%s\n", policy.SchemaVersion, policy.VersionID, digest)
	output.WriteString("worker_processes 1;\n")
	output.WriteString("worker_shutdown_timeout 8s;\n")
	output.WriteString("error_log stderr notice;\n")
	if policy.HTTP3Enabled() {
		output.WriteString("quic_bpf on;\n")
	}
	fmt.Fprintf(&output, "events { worker_connections %d; }\n", policy.Limits.WorkerConnections)
	output.WriteString("http {\n")
	output.WriteString("    access_log /dev/stdout combined;\n")
	fmt.Fprintf(&output, "    client_body_temp_path %s/client-body;\n", nginxTemporaryRoot)
	fmt.Fprintf(&output, "    proxy_temp_path %s/proxy;\n", nginxTemporaryRoot)
	fmt.Fprintf(&output, "    fastcgi_temp_path %s/fastcgi;\n", nginxTemporaryRoot)
	fmt.Fprintf(&output, "    uwsgi_temp_path %s/uwsgi;\n", nginxTemporaryRoot)
	fmt.Fprintf(&output, "    scgi_temp_path %s/scgi;\n", nginxTemporaryRoot)
	output.WriteString("    server_tokens off;\n")
	fmt.Fprintf(&output, "    keepalive_timeout %dms;\n", policy.Limits.IdleTimeoutMS)
	fmt.Fprintf(&output, "    client_header_buffer_size %d;\n", policy.Limits.RequestHeaderBytes)
	fmt.Fprintf(&output, "    large_client_header_buffers 1 %d;\n", policy.Limits.RequestHeaderBytes)
	if policy.HTTP3Enabled() {
		fmt.Fprintf(&output, "    http3_stream_buffer_size %d;\n", http3StreamBufferBytes)
		fmt.Fprintf(&output, "    http3_max_concurrent_streams %d;\n", policy.Limits.ConcurrentStreams)
		fmt.Fprintf(&output, "    quic_active_connection_id_limit %d;\n", policy.Limits.ActiveConnectionIDs)
	}
	output.WriteString("    limit_conn_zone $binary_remote_addr zone=http3_client:64k;\n")
	output.WriteString("    limit_conn_status 503;\n")
	output.WriteString("    server {\n")
	fmt.Fprintf(&output, "        listen %s ssl; # TCP HTTP/2 and HTTP/1.1 fallback\n", listen)
	if policy.HTTP3Enabled() {
		fmt.Fprintf(&output, "        listen %s quic reuseport; # UDP HTTP/3\n", listen)
	}
	fmt.Fprintf(&output, "        server_name %s;\n", policy.Listener.ServerName)
	output.WriteString("        http2 on;\n")
	if policy.HTTP3Enabled() {
		output.WriteString("        http3 on;\n")
		output.WriteString("        quic_retry on;\n")
		fmt.Fprintf(&output, "        quic_host_key %s;\n", releaseQUICHostKeyFile)
	} else {
		output.WriteString("        http3 off;\n")
	}
	output.WriteString("        ssl_protocols TLSv1.3;\n")
	output.WriteString("        ssl_early_data off;\n")
	output.WriteString("        ssl_session_tickets off;\n")
	fmt.Fprintf(&output, "        ssl_certificate %s;\n", releaseCertificatePath)
	fmt.Fprintf(&output, "        ssl_certificate_key %s;\n", releasePrivateKeyPath)
	fmt.Fprintf(&output, "        limit_conn http3_client %d;\n", policy.Limits.ConnectionsPerClient)
	if policy.HTTP3Enabled() {
		fmt.Fprintf(&output, "        add_header Alt-Svc 'h3=\":%d\"; ma=%d' always;\n", policy.Listener.Port, policy.Listener.AltSvcMaxAgeSeconds)
		fmt.Fprintf(&output, "        add_header X-CDNCA-HTTP3-Version %s always;\n", policy.VersionID)
	}
	output.WriteString("        location = /hold {\n")
	output.WriteString("            echo_sleep 2;\n")
	fmt.Fprintf(&output, "            echo 'version=%s protocol=$server_protocol connection=$connection remote=$remote_addr:$remote_port';\n", policy.VersionID)
	output.WriteString("        }\n")
	output.WriteString("        location / {\n")
	fmt.Fprintf(&output, "            return 200 'version=%s protocol=$server_protocol connection=$connection remote=$remote_addr:$remote_port\\n';\n", policy.VersionID)
	output.WriteString("        }\n")
	output.WriteString("    }\n")
	output.WriteString("}\n")
	return []byte(output.String())
}

func nginxAddress(address string, port int) string {
	if netip.MustParseAddr(address).Is6() {
		return fmt.Sprintf("[%s]:%d", address, port)
	}
	return fmt.Sprintf("%s:%d", address, port)
}
