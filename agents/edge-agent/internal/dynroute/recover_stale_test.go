// 节点开过托管 WAF 后，uninstall --purge 删了 /var/lib/cdnca-edge（WAF 扩展在里面）
// 但留下 /var/lib/dynroute。新 agent 的 Recover 拿旧 nginx.conf 起 OpenResty，load_module 指向已删的
// ngx_http_modsecurity_module.so，dlopen 失败，agent 反复退出。冷启动时旧配置引用的文件不在就丢弃旧配置，
// 等新发布（和从没应用过一样）；文件都在照旧启动。

// staleRuntime is a runtime whose OpenResty is a script that records its
// arguments and refuses (a real start is not needed to tell "started" from
// "discarded").
func staleRuntime(t *testing.T) (*Runtime, string, string) {
	t.Helper()
	root := t.TempDir()
	marker := filepath.Join(root, "openresty-called")
	binary := filepath.Join(root, "openresty")
	script := "#!/bin/sh\nprintf '%s\\n' \"$*\" >>" + marker + "\necho 'fake openresty refused' >&2\nexit 1\n"
	if err := os.WriteFile(binary, []byte(script), 0o755); err != nil {
		t.Fatal(err)
	}
	runtime, err := New(Config{StateRoot: filepath.Join(root, "node"), SharedRoot: filepath.Join(root, "shared"),
		LuaRoot: root, OpenResty: binary, WorkerGID: -1})
	if err != nil {
		t.Fatal(err)
	}
	return runtime, root, marker
}

func writeFile(t *testing.T, path, content string) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(content), 0o640); err != nil {
		t.Fatal(err)
	}
}

// wafConf is the shape the skeleton renders for a managed WAF node.
func wafConf(engine, rules, placeholder string) string {
	return "# generated by cdnca node skeleton (site_runtime 9); no site is compiled in\n" +
		"load_module \"" + engine + "/modules/ngx_http_modsecurity_module.so\";\n" +
		"http {\n  access_log off;\n" +
		"  modsecurity_rules 'SecUnicodeMapFile " + engine + "/unicode.mapping 20127';\n" +
		"  modsecurity_rules_file \"" + rules + "\";\n" +
		"  server {\n    listen 443 ssl;\n    ssl_certificate \"" + placeholder + ".crt\";\n    ssl_certificate_key \"" + placeholder + ".key\";\n" +
		"    location @waf-pl1 {\n      modsecurity on;\n      modsecurity_rules_file \"" + filepath.Dir(rules) + "/tiers/pl1.conf\";\n" +
		"      modsecurity_transaction_id $cdnca_waf_tx;\n    }\n  }\n}\n"
}

func seedStaleState(t *testing.T, runtime *Runtime) {
	t.Helper()
	runtime.state = persisted{Generation: 7, Skeleton: "old-skeleton", WAF: "old-waf", L4: "dynroute-l4-old", L4Ports: []int{8443},
		Scopes: map[string]scopeIdentity{"scope": {}}}
	if err := runtime.saveState(); err != nil {
		t.Fatal(err)
	}
}

func TestRecoverDiscardsAConfigurationWhoseWAFModuleWasPurged(t *testing.T) {
	runtime, root, marker := staleRuntime(t)
	waf := filepath.Join(runtime.config.StateRoot, "managed-waf", "v1")
	writeFile(t, filepath.Join(waf, "rules.conf"), "Include "+filepath.Join(root, "gone", "crs", "REQUEST-901.conf")+"\n")
	writeFile(t, filepath.Join(waf, "tiers", "pl1.conf"), "SecRuleEngine On\n")
	placeholder := filepath.Join(runtime.config.StateRoot, "placeholder")
	writeFile(t, runtime.confPath(), wafConf(filepath.Join(root, "gone"), filepath.Join(waf, "rules.conf"), placeholder))
	seedStaleState(t, runtime)

	if err := runtime.Recover(context.Background()); err != nil {
		t.Fatalf("Recover: %v", err)
	}
	if _, err := os.Stat(marker); !os.IsNotExist(err) {
		t.Fatalf("OpenResty was started with the stale configuration: %v", err)
	}
	if runtime.Applied() {
		t.Fatal("stale nginx.conf still in place")
	}
	if _, err := os.Stat(runtime.confPath() + ".stale"); err != nil {
		t.Fatalf("stale configuration not kept aside: %v", err)
	}
	// the next Apply starts like a fresh node: nothing of the old runtime is
	// taken as installed (L4 release, skeleton), the generation keeps counting
	raw, err := os.ReadFile(runtime.statePath())
	if err != nil {
		t.Fatal(err)
	}
	var saved persisted
	if err := json.Unmarshal(raw, &saved); err != nil {
		t.Fatal(err)
	}
	if saved.Generation != 7 || saved.Skeleton != "" || saved.WAF != "" || saved.L4 != "" || len(saved.L4Ports) != 0 || len(saved.Scopes) != 0 {
		t.Fatalf("state not reset: %+v", saved)
	}
	if runtime.state.Generation != 7 || runtime.state.L4 != "" {
		t.Fatalf("in-memory state not reset: %+v", runtime.state)
	}
}

func TestRecoverDiscardsAConfigurationWhoseCRSIncludeWasPurged(t *testing.T) {
	runtime, root, marker := staleRuntime(t)
	engine := filepath.Join(root, "engine")
	writeFile(t, filepath.Join(engine, "modules", "ngx_http_modsecurity_module.so"), "elf")
	writeFile(t, filepath.Join(engine, "unicode.mapping"), "map")
	waf := filepath.Join(runtime.config.StateRoot, "managed-waf", "v1")
	writeFile(t, filepath.Join(waf, "rules.conf"), "SecRuleEngine DetectionOnly\n")
	// the tier file includes the CRS rules of the purged extension
	writeFile(t, filepath.Join(waf, "tiers", "pl1.conf"), "# tier\nInclude "+filepath.Join(root, "gone", "rules", "REQUEST-942-APPLICATION-ATTACK-SQLI.conf")+"\n")
	writeFile(t, runtime.confPath(), wafConf(engine, filepath.Join(waf, "rules.conf"), filepath.Join(runtime.config.StateRoot, "placeholder")))

	if err := runtime.Recover(context.Background()); err != nil {
		t.Fatalf("Recover: %v", err)
	}
	if _, err := os.Stat(marker); !os.IsNotExist(err) || runtime.Applied() {
		t.Fatalf("stale configuration was used (marker %v, applied %v)", err, runtime.Applied())
	}
}

func TestRecoverStartsAConfigurationWhoseFilesAreAllPresent(t *testing.T) {
	runtime, root, marker := staleRuntime(t)
	engine := filepath.Join(root, "engine")
	writeFile(t, filepath.Join(engine, "modules", "ngx_http_modsecurity_module.so"), "elf")
	writeFile(t, filepath.Join(engine, "unicode.mapping"), "map")
	crs := filepath.Join(root, "crs", "REQUEST-901.conf")
	writeFile(t, crs, "# crs\n")
	waf := filepath.Join(runtime.config.StateRoot, "managed-waf", "v1")
	writeFile(t, filepath.Join(waf, "rules.conf"), "Include "+crs+"\n")
	writeFile(t, filepath.Join(waf, "tiers", "pl1.conf"), "Include "+crs+"\n")
	writeFile(t, runtime.confPath(), wafConf(engine, filepath.Join(waf, "rules.conf"), filepath.Join(runtime.config.StateRoot, "placeholder")))
	seedStaleState(t, runtime)

	err := runtime.Recover(context.Background())
	if err == nil || !strings.Contains(err.Error(), "fake openresty refused") {
		t.Fatalf("OpenResty not started with the intact configuration: %v", err)
	}
	called, readErr := os.ReadFile(marker)
	if readErr != nil || !strings.Contains(string(called), runtime.confPath()) {
		t.Fatalf("OpenResty arguments %q %v", called, readErr)
	}
	if !runtime.Applied() || runtime.state.L4 != "dynroute-l4-old" {
		t.Fatalf("an intact configuration was discarded (applied %v, state %+v)", runtime.Applied(), runtime.state)
	}
}

func TestMissingConfigurationReferencesSkipsVariablesAndRelativePaths(t *testing.T) {
	root := t.TempDir()
	present := filepath.Join(root, "present.pem")
	writeFile(t, present, "pem")
	conf := filepath.Join(root, "nginx.conf")
	writeFile(t, conf, "ssl_certificate $cdnca_cert;\nssl_certificate_key data:$cdnca_key;\ninclude mime.types;\n"+
		"proxy_ssl_trusted_certificate \""+present+"\";\n# load_module /gone/commented.so;\n")
	if missing := missingConfigurationReference(conf); missing != "" {
		t.Fatalf("missing %q", missing)
	}
	writeFile(t, conf, "include "+filepath.Join(root, "gone.conf")+";\n")
	if missing := missingConfigurationReference(conf); missing != filepath.Join(root, "gone.conf") {
		t.Fatalf("missing %q", missing)
	}
	// a line longer than any scanner buffer (a large Lua block) is read whole
	writeFile(t, conf, "init_by_lua_block { local x = '"+strings.Repeat("a", 8<<20)+"' }\ninclude "+filepath.Join(root, "gone.conf")+";\n")
	if missing := missingConfigurationReference(conf); missing != filepath.Join(root, "gone.conf") {
		t.Fatalf("long line: missing %q", missing)
	}
	// an unreadable configuration is left to OpenResty
	if missing := missingConfigurationReference(filepath.Join(root, "absent.conf")); missing != "" {
		t.Fatalf("absent configuration: %q", missing)
	}
}
