func CompileJSON(raw []byte, paths RuntimePaths) (Artifact, error) {
	if len(raw) == 0 || len(raw) > MaxPolicyBytes {
		return Artifact{}, invalid("policy size must be between 1 and %d bytes", MaxPolicyBytes)
	}
	if err := rejectDuplicateJSONKeys(raw); err != nil {
		return Artifact{}, err
	}
	decoder := json.NewDecoder(bytes.NewReader(raw))
	decoder.DisallowUnknownFields()
	var policy Policy
	if err := decoder.Decode(&policy); err != nil {
		return Artifact{}, invalid("decode policy: %v", err)
	}
	if err := requireJSONEOF(decoder); err != nil {
		return Artifact{}, err
	}
	return Compile(policy, paths)
}

func Compile(input Policy, paths RuntimePaths) (Artifact, error) {
	policy, err := normalizePolicy(input)
	if err != nil {
		return Artifact{}, err
	}
	if err := validateRuntimePaths(paths); err != nil {
		return Artifact{}, err
	}
	canonical, err := json.Marshal(policy)
	if err != nil {
		return Artifact{}, fmt.Errorf("marshal canonical cache freshness policy: %w", err)
	}
	canonical = append(canonical, '\n')
	nginx := compileNginx(policy, paths)
	digestInput := make([]byte, 0, len(canonical)+len(nginx))
	digestInput = append(digestInput, canonical...)
	digestInput = append(digestInput, nginx...)
	return Artifact{
		PolicyVersion:   policy.PolicyVersion,
		CanonicalPolicy: canonical,
		Nginx:           nginx,
		Digest:          sha256.Sum256(digestInput),
	}, nil
}

func normalizePolicy(input Policy) (Policy, error) {
	return edgeconfig.NormalizeCacheFreshnessPolicy(input)
}

func compileNginx(policy Policy, paths RuntimePaths) []byte {
	var output bytes.Buffer
	fmt.Fprintf(&output, "# generated by cdnca edge-agent cachefreshness schema=%s version=%d\n", SchemaVersion, policy.PolicyVersion)
	output.WriteString("worker_processes auto;\n")
	fmt.Fprintf(&output, "pid %s;\n", nginxQuote(filepath.Join(paths.StateRoot, "cache-freshness.pid")))
	fmt.Fprintf(&output, "error_log %s notice;\n", nginxQuote(filepath.Join(paths.StateRoot, "error.log")))
	output.WriteString("events { worker_connections 4096; }\nhttp {\n")
	output.WriteString("  access_log off;\n  server_tokens off;\n  gzip off;\n")
	output.WriteString("  variables_hash_max_size 4096;\n  variables_hash_bucket_size 128;\n")
	fmt.Fprintf(&output, "  proxy_cache_path %s levels=1:2 keys_zone=cache_freshness:16m inactive=%ds max_size=%d use_temp_path=off;\n",
		nginxQuote(filepath.Join(paths.StateRoot, "cache")), policy.CacheInactiveSeconds, policy.CacheMaxBytes)
	fmt.Fprintf(&output, "  proxy_temp_path %s;\n", nginxQuote(filepath.Join(paths.StateRoot, "proxy_temp")))
	writeMaps(&output)
	if policy.Enhancement.Enabled {
		output.WriteString("  map \"$upstream_http_etag|$upstream_http_last_modified|$upstream_http_content_length|$upstream_http_date\" $cache_freshness_validator_bypass { default 0; \"|||\" 1; }\n")
		if policy.FollowOriginHeaders {
			output.WriteString("  map $upstream_http_vary $cache_freshness_enhancement_vary_bypass { default 0; ~*^\\s*\\*\\s*$ 1; }\n")
		} else {
			output.WriteString("  map $upstream_http_vary $cache_freshness_enhancement_vary_bypass { default 1; \"\" 0; }\n")
		}
	}
	if policy.Enhancement.Enabled || policy.FollowOriginHeaders {
		fmt.Fprintf(&output, "  lua_package_path %s;\n", nginxQuote(filepath.Join(paths.LuaRoot, "?.lua")+";;"))
	}
	if policy.Enhancement.Enabled {
		output.WriteString("  lua_shared_dict cache_freshness_meta 16m;\n")
		output.WriteString("  init_worker_by_lua_block { require(\"guard\").init_worker() }\n")
	}
	fmt.Fprintf(&output, "  upstream cache_freshness_origin { server %s; keepalive 16; }\n", originAddress(policy.OriginHost, policy.OriginPort))
	output.WriteString("  server {\n")
	fmt.Fprintf(&output, "    listen %s default_server;\n", listener(policy.ListenAddress, policy.ListenPort))
	output.WriteString("    server_name _; return 421;\n")
	output.WriteString("  }\n")
	output.WriteString("  server {\n")
	fmt.Fprintf(&output, "    listen %s;\n", listener(policy.ListenAddress, policy.ListenPort))
	fmt.Fprintf(&output, "    server_name %s;\n", strings.Join(policy.Hosts, " "))
	fmt.Fprintf(&output, "    set $cache_freshness_policy_version %d;\n", policy.PolicyVersion)
	output.WriteString("    location = /_cdnca/cache-freshness-healthz { default_type text/plain; return 200 \"ok:$cache_freshness_policy_version\\n\"; }\n")
	output.WriteString("    location / {\n")
	output.WriteString("      set $cache_freshness_method GET;\n")
	output.WriteString("      if ($request_method !~ ^(GET|HEAD)$) { set $cache_freshness_method BYPASS; }\n")
	identity := fmt.Sprintf("v=1|tenant=%s|site=%s|config=%d|scheme=$scheme|host=$host|port=$server_port|method=$cache_freshness_method|request=$request_uri",
		policy.TenantID, policy.SiteID, policy.ConfigurationVersion)
	fmt.Fprintf(&output, "      set $cache_freshness_identity %s;\n", nginxQuote(identity))
	output.WriteString("      set $cache_freshness_hard_bypass 0;\n")
	if policy.Enhancement.Enabled {
		output.WriteString("      set $cache_freshness_generation \"\";\n")
		output.WriteString("      set $cache_freshness_object_token \"\";\n")
		output.WriteString("      set $cache_freshness_fail_closed 0;\n")
		output.WriteString("      rewrite_by_lua_block { require(\"guard\").access({ identity = ngx.var.cache_freshness_identity, request_bypass = ngx.var.cache_freshness_request_bypass == \"1\", ")
		if policy.FollowOriginHeaders {
			output.WriteString("follow_origin_headers = true, ")
		}
		output.WriteString("fresh_seconds = ")
		fmt.Fprintf(&output, "%d, stale_seconds = %d, lock_seconds = %.3f, metadata_ttl_seconds = %d }) }\n", policy.FreshSeconds, policy.Enhancement.StaleWindowSeconds, float64(policy.Enhancement.Expert.LockAgeMilliseconds)/1000, policy.CacheInactiveSeconds+60)
		output.WriteString("      header_filter_by_lua_block { require(\"guard\").header_filter({ identity = ngx.var.cache_freshness_identity, response_bypass = ngx.var.cache_freshness_response_bypass == \"1\", validator_bypass = ngx.var.cache_freshness_validator_bypass == \"1\", vary_bypass = ngx.var.cache_freshness_enhancement_vary_bypass == \"1\", ")
		if policy.FollowOriginHeaders {
			output.WriteString("follow_origin_headers = true, ")
		}
		output.WriteString("fresh_seconds = ")
		fmt.Fprintf(&output, "%d, stale_seconds = %d, lock_timeout_seconds = %.3f, metadata_ttl_seconds = %d }) }\n", policy.FreshSeconds, policy.Enhancement.StaleWindowSeconds, float64(policy.Enhancement.Expert.LockTimeoutMilliseconds)/1000, policy.CacheInactiveSeconds+60)
		output.WriteString("      body_filter_by_lua_block { require(\"guard\").body_filter() }\n")
		output.WriteString("      log_by_lua_block { require(\"guard\").log({ identity = ngx.var.cache_freshness_identity }) }\n")
	} else if policy.FollowOriginHeaders {
		output.WriteString("      set $cache_freshness_fail_closed 0;\n")
		output.WriteString("      header_filter_by_lua_block { require(\"guard\").origin_header_filter({ follow_origin_headers = true }) }\n")
	}
	output.WriteString("      proxy_http_version 1.1;\n      proxy_set_header Connection \"\";\n      proxy_set_header Host $host;\n")
	output.WriteString("      proxy_cache cache_freshness;\n")
	cacheKey := identity
	if policy.Enhancement.Enabled {
		cacheKey = "$cache_freshness_generation|$cache_freshness_object_token|" + identity
	}
	fmt.Fprintf(&output, "      proxy_cache_key %s;\n", nginxQuote(cacheKey))
	output.WriteString("      proxy_cache_methods GET HEAD;\n      proxy_cache_convert_head on;\n")
	output.WriteString("      proxy_hide_header X-CDNCA-Cache-Reason;\n")
	output.WriteString("      proxy_hide_header X-CDNCA-Cache-State;\n")
	output.WriteString("      proxy_hide_header X-CDNCA-Cache-Policy;\n")
	output.WriteString("      proxy_hide_header X-CDNCA-Cache-Status;\n")
	if policy.Enhancement.Enabled {
		output.WriteString("      proxy_cache_bypass $cache_freshness_request_bypass $cache_freshness_hard_bypass $cache_freshness_fail_closed;\n")
		output.WriteString("      proxy_no_cache $cache_freshness_request_bypass $cache_freshness_response_bypass $cache_freshness_validator_bypass $cache_freshness_enhancement_vary_bypass $cache_freshness_fail_closed;\n")
	} else if policy.FollowOriginHeaders {
		output.WriteString("      proxy_cache_bypass $cache_freshness_request_bypass $cache_freshness_hard_bypass;\n")
		output.WriteString("      proxy_no_cache $cache_freshness_request_bypass $cache_freshness_response_bypass $cache_freshness_fail_closed;\n")
	} else {
		output.WriteString("      proxy_cache_bypass $cache_freshness_request_bypass $cache_freshness_hard_bypass;\n")
		output.WriteString("      proxy_no_cache $cache_freshness_request_bypass $cache_freshness_response_bypass;\n")
	}
	if policy.Enhancement.Enabled {
		expert := policy.Enhancement.Expert
		output.WriteString("      proxy_cache_lock on;\n")
		fmt.Fprintf(&output, "      proxy_cache_lock_timeout %s;\n", nginxDuration(expert.LockTimeoutMilliseconds))
		fmt.Fprintf(&output, "      proxy_cache_lock_age %s;\n", nginxDuration(expert.LockAgeMilliseconds))
		if *expert.BackgroundUpdate {
			output.WriteString("      proxy_cache_background_update on;\n")
		} else {
			output.WriteString("      proxy_cache_background_update off;\n")
		}
		if len(expert.FailureClasses) > 0 {
			classes := make([]string, len(expert.FailureClasses))
			for index, class := range expert.FailureClasses {
				classes[index] = string(class)
			}
			fmt.Fprintf(&output, "      proxy_cache_use_stale %s;\n", strings.Join(classes, " "))
		}
		if *expert.Revalidation {
			output.WriteString("      proxy_cache_revalidate on;\n")
		} else {
			output.WriteString("      proxy_cache_revalidate off;\n")
		}
	}
	if !policy.FollowOriginHeaders {
		fmt.Fprintf(&output, "      proxy_cache_valid 200 %ds;\n", policy.FreshSeconds)
	}
	if !policy.Enhancement.Enabled {
		output.WriteString("      add_header X-CDNCA-Cache-Reason $cache_freshness_cache_reason always;\n")
		output.WriteString("      add_header X-CDNCA-Cache-State $cache_freshness_cache_state always;\n")
	}
	output.WriteString("      proxy_pass http://cache_freshness_origin;\n")
	output.WriteString("    }\n  }\n}\n")
	return append([]byte(nil), output.Bytes()...)
}

func writeMaps(output *bytes.Buffer) {
	output.WriteString("  map $request_method $cache_freshness_method_bypass { default 1; GET 0; HEAD 0; }\n")
	for _, item := range []struct{ source, name string }{
		{"$http_authorization", "authorization"}, {"$http_cookie", "cookie"}, {"$http_upgrade", "upgrade"},
		{"$http_range", "range"}, {"$http_if_range", "if_range"}, {"$http_if_match", "if_match"},
		{"$http_if_none_match", "if_none_match"}, {"$http_if_modified_since", "if_modified_since"},
		{"$http_if_unmodified_since", "if_unmodified_since"},
	} {
		fmt.Fprintf(output, "  map %s $cache_freshness_%s_bypass { default 1; \"\" 0; }\n", item.source, item.name)
	}
	output.WriteString("  map $http_cache_control $cache_freshness_request_cc_bypass { default 0; ~*(^|,)\\s*(private|no-store|no-cache)(\\s*(=|,|$)) 1; }\n")
	output.WriteString("  map $http_pragma $cache_freshness_pragma_bypass { default 0; ~*no-cache 1; }\n")
	output.WriteString("  map \"$cache_freshness_method_bypass$cache_freshness_authorization_bypass$cache_freshness_cookie_bypass$cache_freshness_upgrade_bypass$cache_freshness_range_bypass$cache_freshness_if_range_bypass$cache_freshness_if_match_bypass$cache_freshness_if_none_match_bypass$cache_freshness_if_modified_since_bypass$cache_freshness_if_unmodified_since_bypass$cache_freshness_request_cc_bypass$cache_freshness_pragma_bypass\" $cache_freshness_request_bypass { default 1; \"000000000000\" 0; }\n")
	output.WriteString("  map $upstream_http_set_cookie $cache_freshness_set_cookie_bypass { default 1; \"\" 0; }\n")
	output.WriteString("  map $upstream_http_cache_control $cache_freshness_response_cc_bypass { default 0; ~*(^|,)\\s*(private|no-store|no-cache)(\\s*(=|,|$)) 1; }\n")
	output.WriteString("  map $upstream_http_vary $cache_freshness_vary_bypass { default 0; ~*^\\s*\\*\\s*$ 1; }\n")
	output.WriteString("  map $status $cache_freshness_status_bypass { default 1; 200 0; }\n")
	output.WriteString("  map \"$cache_freshness_set_cookie_bypass$cache_freshness_response_cc_bypass$cache_freshness_vary_bypass$cache_freshness_status_bypass\" $cache_freshness_response_bypass { default 1; \"0000\" 0; }\n")
	output.WriteString("  map $upstream_cache_status $cache_freshness_cache_reason { default origin_error; \"\" cache_request_bypass; HIT cache_fresh_hit; MISS cache_miss; BYPASS cache_request_bypass; EXPIRED cache_miss; STALE stale_served_revalidate; UPDATING stale_served_revalidate; REVALIDATED cache_fresh_hit; }\n")
	output.WriteString("  map $cache_freshness_cache_reason $cache_freshness_cache_state { default expired; cache_fresh_hit fresh; coalesced_follower fresh; stale_served_revalidate stale; }\n")
}

func validateRuntimePaths(paths RuntimePaths) error {
	for field, value := range map[string]string{"state_root": paths.StateRoot, "lua_root": paths.LuaRoot} {
		if !filepath.IsAbs(value) || filepath.Clean(value) != value || value == string(filepath.Separator) || strings.ContainsAny(value, "\x00\r\n\"'$;{}") {
			return invalid("%s must be a clean absolute non-root path", field)
		}
	}
	return nil
}

func listener(host string, port uint16) string {
	if address, err := netip.ParseAddr(host); err == nil && address.Is6() {
		return "[" + host + "]:" + strconv.Itoa(int(port))
	}
	return host + ":" + strconv.Itoa(int(port))
}

func originAddress(host string, port uint16) string { return listener(host, port) }

func nginxDuration(milliseconds uint32) string {
	if milliseconds%1000 == 0 {
		return strconv.FormatUint(uint64(milliseconds/1000), 10) + "s"
	}
	return strconv.FormatUint(uint64(milliseconds), 10) + "ms"
}

func nginxQuote(value string) string {
	return "\"" + strings.NewReplacer("\\", "\\\\", "\"", "\\\"").Replace(value) + "\""
}

func invalid(format string, values ...any) error {
	return errors.Join(ErrInvalidPolicy, fmt.Errorf(format, values...))
}

func requireJSONEOF(decoder *json.Decoder) error {
	var extra any
	if err := decoder.Decode(&extra); err == io.EOF {
		return nil
	} else if err != nil {
		return invalid("decode trailing policy data: %v", err)
	}
	return invalid("policy contains trailing JSON value")
}
