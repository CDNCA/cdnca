package l4runtime

import (
	"crypto/sha256"
	"fmt"
	"net/netip"
	"strings"
)

func Compile(config Config) (CompiledConfig, error) {
	normalized, digest, canonical, err := normalize(config)
	if err != nil {
		return CompiledConfig{}, err
	}
	return CompiledConfig{
		Config: normalized, Digest: digest, CanonicalJSON: canonical,
		NginxConfig: render(normalized, digest),
	}, nil
}

func render(config Config, digest string) []byte {
	poolNames := make(map[string]string, len(config.UpstreamPools))
	poolSizes := make(map[string]int, len(config.UpstreamPools))
	referencedPools := make(map[string]struct{}, len(config.Listeners))
	for _, listener := range config.Listeners {
		if !listener.Disabled {
			referencedPools[listener.UpstreamPoolID] = struct{}{}
		}
	}
	var output strings.Builder
	fmt.Fprintf(&output, "# Generated by CDNCA edge-agent; do not edit.\n")
	fmt.Fprintf(&output, "# schema=%s version=%s digest=%s\n", config.SchemaVersion, config.VersionID, digest)
	output.WriteString("worker_processes auto;\n")
	output.WriteString("error_log stderr notice;\n")
	output.WriteString("events {\n    worker_connections 65535;\n}\n")
	output.WriteString("stream {\n")
	output.WriteString("    log_format l4_audit escape=json '{\"time\":\"$time_iso8601\",\"connection\":\"$connection\",\"protocol\":\"$protocol\",\"remote_addr\":\"$remote_addr\",\"proxy_protocol_addr\":\"$proxy_protocol_addr\",\"server_addr\":\"$server_addr\",\"server_port\":\"$server_port\",\"status\":\"$status\",\"bytes_sent\":$bytes_sent,\"bytes_received\":$bytes_received,\"session_time\":$session_time,\"upstream_addr\":\"$upstream_addr\"}';\n\n")
	for _, pool := range config.UpstreamPools {
		if _, referenced := referencedPools[pool.ID]; !referenced {
			continue
		}
		name := internalName("l4_upstream", pool.ID)
		poolNames[pool.ID] = name
		poolSizes[pool.ID] = len(pool.Endpoints)
		fmt.Fprintf(&output, "    # upstream_pool id=%s\n", pool.ID)
		fmt.Fprintf(&output, "    upstream %s {\n", name)
		fmt.Fprintf(&output, "        zone %s 64k;\n", name)
		for _, endpoint := range pool.Endpoints {
			fmt.Fprintf(&output, "        server %s weight=%d max_fails=%d fail_timeout=%ds",
				nginxAddress(endpoint.Address, endpoint.Port), endpoint.Weight, endpoint.MaxFails, endpoint.FailTimeoutMS/1_000)
			if endpoint.Backup {
				output.WriteString(" backup")
			}
			output.WriteString(";\n")
		}
		output.WriteString("    }\n\n")
	}
	output.WriteString("    limit_conn_zone \"$server_addr:$server_port:$protocol:$binary_remote_addr\" zone=l4_limit_clients:16m;\n")
	output.WriteByte('\n')
	for _, listener := range config.Listeners {
		if listener.Disabled {
			continue
		}
		fmt.Fprintf(&output, "    # listener id=%s protocol=%s upstream_pool=%s\n", listener.ID, listener.Protocol, listener.UpstreamPoolID)
		output.WriteString("    server {\n")
		fmt.Fprintf(&output, "        listen %s", nginxAddress(listener.Address, listener.Port))
		if netip.MustParseAddr(listener.Address).Is6() {
			output.WriteString(" ipv6only=on")
		}
		if listener.Protocol == ProtocolUDP {
			output.WriteString(" udp")
		}
		if listener.ProxyProtocolInbound {
			output.WriteString(" proxy_protocol")
		}
		output.WriteString(";\n")
		for _, trustedProxyCIDR := range listener.TrustedProxyCIDRs {
			fmt.Fprintf(&output, "        set_real_ip_from %s;\n", trustedProxyCIDR)
		}
		fmt.Fprintf(&output, "        proxy_pass %s;\n", poolNames[listener.UpstreamPoolID])
		fmt.Fprintf(&output, "        proxy_connect_timeout %dms;\n", listener.ConnectTimeoutMS)
		fmt.Fprintf(&output, "        proxy_timeout %dms;\n", listener.IdleTimeoutMS)
		output.WriteString("        proxy_next_upstream on;\n")
		fmt.Fprintf(&output, "        proxy_next_upstream_tries %d;\n", poolSizes[listener.UpstreamPoolID])
		if listener.Protocol == ProtocolUDP {
			output.WriteString("        proxy_responses 1;\n")
		}
		if listener.ProxyProtocolOutbound {
			output.WriteString("        proxy_protocol on;\n")
		}
		fmt.Fprintf(&output, "        limit_conn l4_limit_clients %d;\n", listener.MaxConnectionsPerClient)
		output.WriteString("        access_log /dev/stdout l4_audit;\n")
		output.WriteString("    }\n\n")
	}
	output.WriteString("}\n")
	return []byte(output.String())
}

func internalName(prefix, id string) string {
	digest := sha256.Sum256([]byte(id))
	return fmt.Sprintf("%s_%x", prefix, digest[:16])
}

func nginxAddress(address string, port int) string {
	if netip.MustParseAddr(address).Is6() {
		return fmt.Sprintf("[%s]:%d", address, port)
	}
	return fmt.Sprintf("%s:%d", address, port)
}
