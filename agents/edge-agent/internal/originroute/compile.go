package originroute

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"fmt"
	"net/netip"
	"path/filepath"
	"strings"

	"github.com/cdnca/cdnca/libs/edgeconfig"
)

func Compile(policy Policy, stateRoot, luaRoot string) (Artifact, error) {
	if !safeAbsolutePath(stateRoot) || !safeAbsolutePath(luaRoot) {
		return Artifact{}, invalid("state and Lua roots must be absolute, clean, injection-safe paths")
	}
	value, err := Normalize(policy)
	if err != nil {
		return Artifact{}, err
	}
	canonical, err := Canonical(value)
	if err != nil {
		return Artifact{}, err
	}
	stateKey, err := edgeconfig.OriginRouteStateKey(originRouteAlgorithmPolicy(value))
	if err != nil {
		return Artifact{}, invalid("build state key: %v", err)
	}
	var output bytes.Buffer
	fmt.Fprintf(&output, "# generated by cdnca originroute schema=%s revision=%d version=%s\n",
		value.Schema, value.Revision, value.VersionID)
	output.WriteString("worker_processes 1;\n")
	fmt.Fprintf(&output, "error_log %s notice;\n", nginxQuote(filepath.Join(stateRoot, "shared", "originroute-error.log")))
	fmt.Fprintf(&output, "pid %s;\n", nginxQuote(filepath.Join(stateRoot, "shared", "originroute.pid")))
	output.WriteString("events { worker_connections 4096; }\nhttp {\n")
	fmt.Fprintf(&output, "  lua_package_path %s;\n", nginxQuote(filepath.Join(luaRoot, "?.lua")+";;"))
	output.WriteString("  lua_shared_dict cdnca_originroute_state 1m;\n")
	if value.DNS != nil {
		output.WriteString("  lua_shared_dict cdnca_originroute_dns_state 8m;\n")
	}
	if value.Adaptive != nil {
		output.WriteString("  lua_shared_dict cdnca_originroute_adaptive_state 2m;\n")
	}
	for _, name := range []string{"client-body", "proxy", "fastcgi", "uwsgi", "scgi"} {
		fmt.Fprintf(&output, "  %s_temp_path %s;\n", strings.ReplaceAll(name, "-", "_"),
			nginxQuote(filepath.Join(stateRoot, "shared", name+"-temp")))
	}
	output.WriteString("  access_log off;\n  server_tokens off;\n")
	output.WriteString("  init_by_lua_block {\n")
	output.WriteString("    local ok, err = require(\"engine\").init_file(ngx.config.prefix() .. \"policy.json\")\n")
	output.WriteString("    if not ok then error(err) end\n  }\n")
	if value.DNS != nil {
		output.WriteString("  init_worker_by_lua_block {\n")
		output.WriteString("    local ok, err = require(\"engine\").start_dns()\n")
		output.WriteString("    if not ok then error(err) end\n  }\n")
	}
	output.WriteString("  upstream cdnca_originroute_dynamic {\n")
	output.WriteString("    server 127.0.0.1:9;\n")
	output.WriteString("    balancer_by_lua_block { require(\"engine\").balance() }\n  }\n")
	for _, listener := range value.Listeners {
		output.WriteString("  server {\n")
		fmt.Fprintf(&output, "    listen %s;\n", nginxListen(listener.Address, listener.Port))
		output.WriteString("    server_name _;\n")
		fmt.Fprintf(&output, "    set $cdnca_origin_state_key %s;\n", nginxQuote(stateKey))
		output.WriteString("    set $cdnca_origin_route \"\";\n")
		output.WriteString("    set $cdnca_origin_event \"\";\n")
		output.WriteString("    set $cdnca_origin_hop \"0\";\n")
		if value.DNS != nil {
			output.WriteString("    set $cdnca_origin_dns_state \"\";\n")
			output.WriteString("    set $cdnca_origin_dns_reason \"\";\n")
		}
		if value.Adaptive != nil {
			output.WriteString("    set $cdnca_origin_reason \"\";\n")
			output.WriteString("    set $cdnca_origin_shadow_reason \"\";\n")
			output.WriteString("    set $cdnca_origin_diagnostic \"\";\n")
		}
		fmt.Fprintf(&output, "    location = /__cdnca_originroute_health { add_header X-CDNCA-Origin-Version %s always; content_by_lua_block { require(\"engine\").health(\"%s\") } }\n",
			nginxQuote(value.VersionID), value.VersionID)
		output.WriteString("    location / {\n")
		fmt.Fprintf(&output, "      access_by_lua_block { require(\"engine\").access(%s) }\n", nginxQuote(listener.ID))
		output.WriteString("      proxy_http_version 1.1;\n")
		output.WriteString("      proxy_set_header Connection \"\";\n")
		output.WriteString("      proxy_set_header X-CDNCA-Origin-Hop $cdnca_origin_hop;\n")
		output.WriteString("      proxy_request_buffering on;\n")
		fmt.Fprintf(&output, "      proxy_connect_timeout %dms;\n", value.Retry.ConnectTimeoutMS)
		fmt.Fprintf(&output, "      proxy_read_timeout %dms;\n", value.Retry.ReadTimeoutMS)
		output.WriteString("      proxy_next_upstream error timeout http_502 http_503 http_504;\n")
		fmt.Fprintf(&output, "      proxy_next_upstream_tries %d;\n", value.Retry.MaxAttempts)
		fmt.Fprintf(&output, "      proxy_next_upstream_timeout %dms;\n", value.Retry.TotalBudgetMS)
		output.WriteString("      proxy_pass http://cdnca_originroute_dynamic;\n")
		output.WriteString("      log_by_lua_block { require(\"engine\").log_result() }\n")
		output.WriteString("    }\n  }\n")
	}
	output.WriteString("}\n")

	hash := sha256.New()
	_, _ = hash.Write(canonical)
	_, _ = hash.Write([]byte{0})
	_, _ = hash.Write(output.Bytes())
	return Artifact{
		VersionID: value.VersionID, Revision: value.Revision,
		Digest: hex.EncodeToString(hash.Sum(nil)), StateKey: stateKey, Policy: canonical,
		Nginx: append([]byte(nil), output.Bytes()...),
	}, nil
}

func safeAbsolutePath(value string) bool {
	return filepath.IsAbs(value) && filepath.Clean(value) == value &&
		!strings.ContainsAny(value, "\x00\r\n\"'$;{}")
}

func nginxListen(address string, port uint16) string {
	value := netip.MustParseAddr(address)
	if value.Is6() {
		return fmt.Sprintf("[%s]:%d", value, port)
	}
	return fmt.Sprintf("%s:%d", value, port)
}

func nginxQuote(value string) string {
	return `"` + strings.NewReplacer(`\`, `\\`, `"`, `\"`, `$`, `\$`).Replace(value) + `"`
}
